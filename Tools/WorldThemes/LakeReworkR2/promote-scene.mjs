import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const main='Assets/01.Scenes/Scenario/OpenWorld/LakeVillageWorld.unity';
const review='Assets/01.Scenes/ArtReview/WorldThemes/LakeReworkR2.unity';
const folder='output/LakeReworkR2/Integration/';
const hash=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex').toUpperCase();
const guid=p=>fs.readFileSync(p+'.meta','utf8').match(/^guid: ([a-f0-9]+)/m)[1];
const baseline=JSON.parse(fs.readFileSync('output/LakeReworkR2/source-hashes.json','utf8').replace(/^\uFEFF/,''));
assert.equal(hash(main),baseline[0].Hash,'정규 씬이 바뀌면 전체 승격 대신 병합 필요');
assert(!fs.existsSync(folder+'main-before.unity'),'중복 적용 금지');
const original=fs.readFileSync(main,'utf8'),approved=fs.readFileSync(review,'utf8');
const ids=s=>new Map([...s.matchAll(/^  _guid: ([^\r\n]+)\r?\n  _ownerKey: GlobalObjectId_V1-\d+-[a-f0-9]+-(\d+-\d+)/gm)].map(m=>[m[2],m[1]]));
for(const [key,value] of ids(original))assert.equal(ids(approved).get(key),value,`진행 ID ${key}`);
const mapping=fs.readFileSync(folder+'asset-map.txt','utf8').replace(/^\uFEFF/,'').trim().split(/\r?\n/).map(s=>s.split(' '));
let promoted=approved.replaceAll(guid(review),guid(main));
for(const [from,to] of mapping)promoted=promoted.replaceAll(from,to);
for(const [from] of mapping)assert(!promoted.includes(from),'검토 전용 참조 잔존');
assert(!promoted.includes(guid(review)),'검토 씬 소유 키 잔존');
fs.copyFileSync(main,folder+'main-before.unity');fs.copyFileSync(main+'.meta',folder+'main-before.unity.meta');
fs.writeFileSync(folder+'approved-source.json',JSON.stringify({mainBefore:hash(main),reviewHash:hash(review),mainGuid:guid(main),reviewGuid:guid(review),mapping,reason:'사용자의 V2 미술 방향 승인 및 정규 씬 적용 지시. TPS 완료 승인 아님.'},null,2));
fs.writeFileSync(folder+'main-promoted.unity',promoted);
fs.copyFileSync(folder+'main-promoted.unity',main);
fs.writeFileSync(folder+'promotion.json',JSON.stringify({main,mainHash:hash(main),sceneGuidPreserved:guid(main),idsPreserved:ids(promoted).size,reviewUnchanged:hash(review)===JSON.parse(fs.readFileSync(folder+'approved-source.json')).reviewHash},null,2));
console.log('정규 씬 저장: GUID·진행 ID 유지, 검토 자원 참조를 정규 복제본으로 전환');
