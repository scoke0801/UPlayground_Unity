import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const root='output/LakeReworkR2/Integration/';
const plan=JSON.parse(fs.readFileSync(root+'approved-source.json'));
const main='Assets/01.Scenes/Scenario/OpenWorld/LakeVillageWorld.unity';
const review='Assets/01.Scenes/ArtReview/WorldThemes/LakeReworkR2.unity';
const hash=v=>crypto.createHash('sha256').update(v).digest('hex').toUpperCase();
const source=fs.readFileSync(root+'main-before.unity','utf8'),current=fs.readFileSync(main,'utf8'),approved=fs.readFileSync(review,'utf8');
let expected=approved.replaceAll(plan.reviewGuid,plan.mainGuid);for(const [from,to] of plan.mapping)expected=expected.replaceAll(from,to);
assert.equal(hash(current),hash(expected),'승인본과 정규 씬의 의미 있는 차이');
assert.equal(hash(approved),plan.reviewHash,'검토 씬 변경');
assert.equal(fs.readFileSync(main+'.meta','utf8'),fs.readFileSync(root+'main-before.unity.meta','utf8'),'정규 씬 GUID 변경');
const ids=s=>new Map([...s.matchAll(/^  _guid: ([^\r\n]+)\r?\n  _ownerKey: GlobalObjectId_V1-\d+-[a-f0-9]+-(\d+-\d+)/gm)].map(m=>[m[2],m[1]]));
const after=ids(current);for(const [key,value] of ids(source))assert.equal(after.get(key),value,`진행 ID ${key}`);
const baseline=JSON.parse(fs.readFileSync('output/LakeReworkR2/source-hashes.json','utf8').replace(/^\uFEFF/,''));
assert.equal(hash(fs.readFileSync('Assets/10.Datas/World/OpenWorld/Terrain.asset')),baseline[1].Hash,'원본 지형 변경');
const renderer=fs.readFileSync('Assets/Settings/PC_Renderer.asset','utf8');
const withoutNewBlur=renderer.replace(/^  - \{fileID: 986250092344022804\}\r?\n/m,'').replace(/^--- !u!114 &986250092344022804\r?\n[\s\S]*?(?=^--- !u!)/m,'');
const report={approvedSceneMatches:true,mainGuidPreserved:true,idsPreserved:after.size,reviewSceneUnchanged:true,originalTerrainUnchanged:true,rendererCurrentHash:hash(renderer),rendererMatchesStartWhenConcurrentBlurAdditionExcluded:hash(withoutNewBlur)===baseline[2].Hash,note:'다른 카메라 작업에서 생성된 SpeedRadialBlur RendererFeature 추가는 되돌리지 않는다. 씬 승인과 TPS 검증은 별도다.'};
fs.writeFileSync(root+'preservation.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report));
