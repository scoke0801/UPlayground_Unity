import {authorUplandDiscovery} from './author-upland-discovery.mjs';
import fs from 'node:fs';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {authorForestDiscovery} from './author-forest-discovery.mjs';
import {authorTradeDiscovery} from './author-trade-discovery.mjs';
import {authorCorridorDiscovery} from './author-corridor-discovery.mjs';
const folder=process.argv[2]||'output/OpenWorld/Exploration/Iteration05';
const baseline='output/OpenWorld/Exploration/Iteration04';
fs.mkdirSync(folder,{recursive:true});
const before=JSON.parse(fs.readFileSync(baseline+'/input-before.json','utf8'));
const current=JSON.parse(fs.readFileSync('Tools/OpenWorld/city-layout.json','utf8'));
assert.deepEqual(authorUplandDiscovery(authorForestDiscovery(structuredClone(before))),current);
assert.deepEqual(authorForestDiscovery(structuredClone(current)),current);
assert.deepEqual(authorCorridorDiscovery(authorTradeDiscovery(structuredClone(current))),current);
for(const field of ['cities','southOrigin','southSize'])assert.deepEqual(current[field],before[field]);
for(const field of ['worldOrigin','worldSize','landforms','platforms','pickups','encounters'])assert.deepEqual(current.landscape[field],before.landscape[field]);
const allowed=['Expansion_log_791','Expansion_log_792','Explore_0617','Explore_0618','Explore_0619','Explore_0014','Explore_0036','Explore_0630','Explore_0631','Explore_0579','Explore_0582','Explore_0624','Explore_0625','Explore_0626','Expansion_rock_345','Expansion_rock_353'];
for(const p of before.landscape.props)if(!allowed.includes(p.id))assert.deepEqual(current.landscape.props.find(q=>q.id===p.id),p);
assert.equal(current.landscape.props.length,before.landscape.props.length-1);
assert.equal(current.landscape.gatherables.length,1);
const ids=[...current.landscape.pickups,...current.landscape.encounters,...current.landscape.gatherables].map(q=>q.id);
assert.equal(new Set(ids).size,ids.length);
const gathering=current.landscape.gatherables[0];
for(const key of ['model','interaction'])assert(fs.existsSync(gathering[key]));
assert.deepEqual(gathering.position,{x:1605,y:0,z:805});
const sourceBefore=JSON.parse(fs.readFileSync(baseline+'/source-before.json','utf8'));
const sourceAfter=Object.fromEntries(Object.keys(sourceBefore).map(p=>[p,crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex')]));
assert.deepEqual(sourceAfter,sourceBefore,'원본 네 씬 보존');
fs.writeFileSync(folder+'/source-comparison.json',JSON.stringify({before:sourceBefore,after:sourceAfter,equal:true},null,2));
const result={utc:new Date().toISOString(),result:'PASS',checks:['최종 입력과 저작 함수 일치','반복 저작 불변','쉼터·회랑 저작 불변','기존 보상·적·ID·도시·면적·지형 보존','수로 행동 데이터/리소스 연결','원본 네 씬 SHA256 일치'],changedProps:allowed,gathering};
fs.writeFileSync(folder+'/authoring-check.json',JSON.stringify(result,null,2));
console.log(result);
