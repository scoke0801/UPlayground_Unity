import {authorUplandDiscovery} from './author-upland-discovery.mjs';
import fs from 'node:fs';
import assert from 'node:assert/strict';
import { authorTradeDiscovery } from './author-trade-discovery.mjs';
import { authorCorridorDiscovery } from './author-corridor-discovery.mjs';
import { authorForestDiscovery } from './author-forest-discovery.mjs';
const folder='output/OpenWorld/Exploration/Iteration02';
const before=JSON.parse(fs.readFileSync(folder+'/input-before.json','utf8'));
const current=JSON.parse(fs.readFileSync('Tools/OpenWorld/city-layout.json','utf8'));
const authored=authorUplandDiscovery(authorForestDiscovery(authorCorridorDiscovery(authorTradeDiscovery(structuredClone(before)))));
assert.deepEqual(authored,current,'최종 입력과 저작 함수 일치');
assert.deepEqual(authorTradeDiscovery(structuredClone(current)),current,'반복 저작 불변');
assert.deepEqual(before.cities,current.cities,'도시 위치·거리·계약 보존');
assert.deepEqual(before.landscape.worldSize,current.landscape.worldSize);
assert.deepEqual(before.landscape.landforms,current.landscape.landforms);
assert.deepEqual(before.landscape.encounters,current.landscape.encounters);
assert.equal(before.landscape.props.length-1,current.landscape.props.length);
assert.deepEqual(before.landscape.pickups.map(p=>[p.id,p.item,p.count]),current.landscape.pickups.map(p=>[p.id,p.item,p.count]));
const changed=current.landscape.props.filter(p=>JSON.stringify(p)!==JSON.stringify(before.landscape.props.find(q=>q.id===p.id)));
assert.equal(changed.length,22);
const result={utc:new Date().toISOString(),result:'PASS',checks:['네 저작 함수와 실제 입력 일치','반복 저작 불변','도시·면적·산체 보존','적 구성 보존','장식 통나무 1개를 채집으로 전환','기존 보상 ID·아이템·수량 보존'],changedPropIds:changed.map(p=>p.id)};
const output=process.argv[2]||'output/OpenWorld/Exploration/Iteration05';
fs.mkdirSync(output,{recursive:true});
fs.writeFileSync(output+'/trade-corridor-regression.json',JSON.stringify(result,null,2)+'\n');
console.log(result);
