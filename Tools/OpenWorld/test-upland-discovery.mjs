import fs from 'node:fs';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {authorUplandDiscovery} from './author-upland-discovery.mjs';
import {authorTradeDiscovery} from './author-trade-discovery.mjs';
import {authorCorridorDiscovery} from './author-corridor-discovery.mjs';
import {authorForestDiscovery} from './author-forest-discovery.mjs';
const folder=process.argv[2]||'output/OpenWorld/Exploration/Iteration05';
fs.mkdirSync(folder,{recursive:true});
const before=JSON.parse(fs.readFileSync(folder+'/input-before.json','utf8'));
const current=JSON.parse(fs.readFileSync('Tools/OpenWorld/city-layout.json','utf8'));
assert.deepEqual(authorUplandDiscovery(structuredClone(before)),current);
assert.deepEqual(authorUplandDiscovery(structuredClone(current)),current);
assert.deepEqual(authorForestDiscovery(authorCorridorDiscovery(authorTradeDiscovery(structuredClone(current)))),current);
for(const field of ['cities','southOrigin','southSize'])assert.deepEqual(current[field],before[field]);
for(const field of ['worldOrigin','worldSize','landforms','platforms','pickups','encounters','gatherables'])assert.deepEqual(current.landscape[field],before.landscape[field]);
const changed=current.landscape.props.filter(p=>JSON.stringify(p)!==JSON.stringify(before.landscape.props.find(q=>q.id===p.id)));
assert.equal(changed.length,9);assert.equal(current.landscape.props.length,before.landscape.props.length);
for(const p of changed)assert(fs.existsSync(p.prefab));
assert.deepEqual(current.routes.filter(q=>q.id!=='upland-lake-loop'),before.routes.filter(q=>q.id!=='upland-lake-loop'));
const loop=current.routes.find(q=>q.id==='upland-lake-loop');
assert(loop.followTerrain);assert.equal(loop.halfWidth,2.5);
assert.deepEqual(loop.points[0],before.routes.find(q=>q.id===loop.id).points[0]);
assert.deepEqual(loop.points.at(-1),before.routes.find(q=>q.id===loop.id).points.at(-1));
assert(loop.points.some(p=>p.x===1310&&p.z===1310));
const sources=JSON.parse(fs.readFileSync(folder+'/source-before.json','utf8').replace(/^\uFEFF/,''));
for(const source of sources)assert.equal(crypto.createHash('sha256').update(fs.readFileSync(source.Path)).digest('hex').toUpperCase(),source.Hash);
const result={utc:new Date().toISOString(),result:'PASS',checks:['반복 저작·네 함수 합성 불변','기존 쉼터·회랑·숲 입력 보존','높이·면적·도시·적·보상·채집·고정 ID 보존','원본 시나리오 씬 SHA256 보존','전망·본길 접속점 보존','기존 리소스 9개 재배치·순환로 노선 변경'],changedPropIds:changed.map(p=>p.id),loop};
fs.writeFileSync(folder+'/authoring-check.json',JSON.stringify(result,null,2)+'\n');
console.log(result);
